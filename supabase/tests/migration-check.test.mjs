import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { test } from 'node:test';
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';
import { pg_trgm } from '@electric-sql/pglite/contrib/pg_trgm';
import { uuid_ossp } from '@electric-sql/pglite/contrib/uuid_ossp';

// In-memory databases only; never connects to Supabase.
const checkFile = new URL('../migration-check/01_structure_health_check.sql', import.meta.url);
const platformFile = new URL('./support/platform.sql', import.meta.url);
const baselinePattern = /(select \$baseline\$\n)[\s\S]*?(\$baseline\$::text as t)/;

const appSchema = `
  CREATE TABLE public.admins (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), username text NOT NULL, role text NOT NULL,
    is_active boolean NOT NULL DEFAULT true);
  CREATE TABLE public.financial_admin_credentials (admin_id uuid PRIMARY KEY REFERENCES public.admins(id), password_hash text);
  CREATE TABLE public.users (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), username text NOT NULL, archived_at timestamptz,
    total_income numeric NOT NULL DEFAULT 0, created_by uuid REFERENCES public.admins(id));
  CREATE TABLE public.financial_employee_credentials (user_id uuid PRIMARY KEY REFERENCES public.users(id), password_hash text);
  CREATE TABLE public.wallets (user_id uuid PRIMARY KEY REFERENCES public.users(id), available_balance numeric NOT NULL DEFAULT 0,
    frozen_balance numeric NOT NULL DEFAULT 0);
  CREATE TABLE public.withdrawals (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid REFERENCES public.users(id),
    amount numeric NOT NULL, status text NOT NULL);
  CREATE TABLE public.wallet_balance_baselines (user_id uuid PRIMARY KEY, available_balance numeric, frozen_balance numeric,
    total_income numeric, last_ledger_id bigint NOT NULL DEFAULT 0);
  CREATE TABLE public.wallet_ledger_entries (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id uuid,
    available_delta numeric NOT NULL DEFAULT 0, frozen_delta numeric NOT NULL DEFAULT 0, income_delta numeric NOT NULL DEFAULT 0);
  CREATE TABLE public.orders (id uuid PRIMARY KEY DEFAULT gen_random_uuid(), user_id uuid REFERENCES public.users(id),
    status text, created_at timestamptz NOT NULL DEFAULT now());
  ALTER TABLE public.orders ENABLE ROW LEVEL SECURITY;
  CREATE POLICY orders_read ON public.orders FOR SELECT TO anon USING (true);
  CREATE FUNCTION public.touch_order() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RETURN NEW; END $$;
  CREATE TRIGGER orders_touch BEFORE INSERT ON public.orders FOR EACH ROW EXECUTE FUNCTION public.touch_order();
  CREATE FUNCTION public.get_order_total(p_user uuid) RETURNS bigint LANGUAGE sql SECURITY DEFINER
    SET search_path = pg_catalog, public AS $$ SELECT count(*) FROM public.orders WHERE user_id = p_user $$;
  REVOKE ALL ON FUNCTION public.get_order_total(uuid) FROM PUBLIC;
  GRANT EXECUTE ON FUNCTION public.get_order_total(uuid) TO anon;
  ALTER PUBLICATION supabase_realtime ADD TABLE public.orders;
  INSERT INTO storage.buckets (id, name, public, file_size_limit) VALUES ('chat-images', 'chat-images', true, null);
  SELECT cron.schedule('process_pending_orders_every_minute', '* * * * *', 'SELECT 1;');
  WITH a AS (INSERT INTO public.admins (username, role) VALUES ('boss', 'super_admin') RETURNING id),
       c AS (INSERT INTO public.financial_admin_credentials SELECT id, 'x' FROM a),
       u AS (INSERT INTO public.users (username, total_income, created_by) SELECT 'emp', 5, id FROM a RETURNING id),
       ec AS (INSERT INTO public.financial_employee_credentials SELECT id, 'x' FROM u),
       w AS (INSERT INTO public.wallets SELECT id, 3, 2 FROM u),
       wd AS (INSERT INTO public.withdrawals (user_id, amount, status) SELECT id, 2, 'pending' FROM u),
       b AS (INSERT INTO public.wallet_balance_baselines SELECT id, 0, 0, 0, 0 FROM u)
  INSERT INTO public.wallet_ledger_entries (user_id, available_delta, frozen_delta, income_delta) SELECT id, 3, 2, 5 FROM u;
`;

async function createDatabase({ withApp = true } = {}) {
  const db = new PGlite({ extensions: { pgcrypto, pg_trgm, uuid_ossp } });
  await db.exec(await readFile(platformFile, 'utf8'));
  await db.exec(`
    ALTER TABLE cron.job ADD COLUMN database text NOT NULL DEFAULT 'postgres', ADD COLUMN username text NOT NULL DEFAULT 'postgres';
    CREATE TABLE cron.job_run_details (runid bigserial PRIMARY KEY, jobid bigint, status text, return_message text,
      start_time timestamptz, end_time timestamptz);
  `);
  if (withApp) await db.exec(appSchema);
  return db;
}

async function runCheck(db, baselineText) {
  let sql = await readFile(checkFile, 'utf8');
  if (baselineText !== undefined) sql = sql.replace(baselinePattern, (_, start, end) => `${start}${baselineText}\n${end}`);
  const results = await db.exec(sql);
  return results.at(-1).rows;
}

async function generateBaseline(db) {
  const rows = await runCheck(db, '');
  assert.equal(rows.length, 1);
  assert.equal(rows[0]['结果'], '基线生成模式');
  return rows[0]['说明'];
}

const failures = (rows) => rows.filter((row) => row['结果'] === '失败');

test('embedded production baseline is present and well formed', async () => {
  const sql = await readFile(checkFile, 'utf8');
  const body = sql.match(baselinePattern)[0].split('\n').filter((line) => line && !line.startsWith('#') && line.includes('|'));
  const sections = new Map();
  for (const line of body) {
    const [section, key, ...parts] = line.split('|');
    assert.ok(key, `missing key: ${line}`);
    assert.ok(parts.length > 0 && parts.every((part) => /^[a-z]+=/.test(part)), `bad attributes: ${line}`);
    sections.set(section, (sections.get(section) ?? 0) + 1);
  }
  assert.equal(sections.get('tables'), 102);
  assert.equal(sections.get('functions'), 429);
  assert.equal(sections.get('cron'), 9);
  assert.equal(sections.get('buckets'), 7);
  assert.equal(sections.get('realtime'), 24);
});

test('runs on an empty target without crashing and reports what is missing', async () => {
  const db = await createDatabase({ withApp: false });
  const rows = await runCheck(db);
  assert.equal(rows[0]['结果'], '总结');
  assert.match(rows[0]['对象'], /存在失败项/);
  const missing = failures(rows).map((row) => row['对象']);
  for (const name of ['public.users', 'public.wallets', 'public.process_pending_orders()', 'process_pending_orders_every_minute', 'announcement-images']) {
    assert.ok(missing.includes(name), `expected missing ${name}`);
  }
  const unchecked = rows.find((row) => row['对象'] === '钱包余额与账本一致');
  assert.equal(unchecked['结果'], '失败');
  assert.equal(unchecked['实际'], '无法检查');
  await db.close();
});

test('a matching baseline passes and every planted change is detected', async () => {
  const db = await createDatabase();
  const baseline = await generateBaseline(db);
  assert.match(baseline, /^#generated /);

  const clean = await runCheck(db, baseline);
  const structureCategories = new Set(['数据表', '函数/RPC', '定时任务', '存储桶', '实时更新表', '自增序列', '数据库扩展']);
  assert.deepEqual(failures(clean).filter((row) => structureCategories.has(row['类别'])), []);
  for (const item of ['钱包余额与账本一致', '员工累计收入与账本一致', '冻结金额等于待处理提款合计', '在职员工都有登录凭据', '至少有一名启用中的超级管理员']) {
    assert.equal(clean.find((row) => row['对象'] === item)['结果'], '通过', item);
  }
  assert.equal(clean.find((row) => row['对象'] === '全部外键关联')['结果'], '通过');
  for (const probe of ['密码加密校验（bcrypt）可用', '登录令牌哈希（SHA-256）可用', '文字相似度搜索可用（pg_trgm）']) {
    assert.equal(clean.find((row) => row['对象'] === probe)['结果'], '通过', probe);
  }

  await db.exec(`
    DROP TRIGGER orders_touch ON public.orders;
    CREATE OR REPLACE FUNCTION public.get_order_total(p_user uuid) RETURNS bigint LANGUAGE sql SECURITY DEFINER
      SET search_path = pg_catalog, public AS $$ SELECT 0::bigint $$;
    GRANT EXECUTE ON FUNCTION public.get_order_total(uuid) TO PUBLIC;
    DROP POLICY orders_read ON public.orders;
    UPDATE storage.buckets SET public = false WHERE id = 'chat-images';
    UPDATE cron.job SET schedule = '*/5 * * * *';
    ALTER PUBLICATION supabase_realtime DROP TABLE public.orders;
    UPDATE public.wallets SET frozen_balance = 9;
  `);
  const changed = await runCheck(db, baseline);
  const found = failures(changed).map((row) => `${row['对象']}|${row['检查内容']}`);
  for (const expected of [
    'public.orders|触发器', 'public.orders|行级权限策略', 'public.get_order_total(uuid)|函数内容',
    'public.get_order_total(uuid)|执行权限', 'chat-images|是否公开', 'process_pending_orders_every_minute|执行频率',
    'public.orders|整项', '冻结金额等于待处理提款合计|问题数量', '钱包余额与账本一致|问题数量',
  ]) {
    assert.ok(found.includes(expected), `expected failure ${expected}; got ${found.join(', ')}`);
  }
  await db.close();
});

const fingerprintFile = new URL('../migration-check/02_data_fingerprint.sql', import.meta.url);
const oldPattern = /(select \$old\$\n)[\s\S]*?(\$old\$::text as t)/;

async function runFingerprint(db, oldText) {
  let sql = await readFile(fingerprintFile, 'utf8');
  if (oldText !== undefined) sql = sql.replace(oldPattern, (_, start, end) => `${start}${oldText}\n${end}`);
  return (await db.exec(sql)).at(-1).rows;
}

test('data fingerprint matches an identical copy and pinpoints changed tables', async () => {
  const db = await createDatabase();
  const first = await runFingerprint(db);
  assert.equal(first[0]['结果'], '本库指纹');
  const fingerprint = first[0]['说明'];
  assert.match(fingerprint, /^v1;/);
  assert.ok(first.some((row) => row['表'] === 'public.wallets' && row['新库行数'] === '1'));

  const same = await runFingerprint(db, `  ${fingerprint.replace(/;/g, ';\n')}  `);
  const summary = same.find((row) => row['结果'] === '总结');
  assert.match(summary['说明'], /^核心业务数据全部一致/);
  assert.ok(same.filter((row) => row['分类'] === '核心业务' && row['表'] !== '数据对比结果').every((row) => row['结果'] === '一致'));

  await db.exec(`
    UPDATE public.wallets SET available_balance = available_balance + 1;
    INSERT INTO public.orders (user_id, status) SELECT id, 'success' FROM public.users;
    DROP TABLE public.withdrawals;
    UPDATE storage.buckets SET public = false;
  `);
  const changed = await runFingerprint(db, fingerprint);
  const byTable = Object.fromEntries(changed.map((row) => [row['表'], row['结果']]));
  assert.equal(byTable['public.wallets'], '内容不同');
  assert.equal(byTable['public.orders'], '行数不同');
  assert.equal(byTable['public.withdrawals'], '新库缺少');
  assert.equal(byTable['storage.buckets'], '内容不同');
  assert.equal(byTable['public.users'], '一致');
  assert.match(changed.find((row) => row['结果'] === '总结')['说明'], /核心业务表有 4 张不一致/);
  await db.close();
});

test('detects orphaned references and sequences that fall behind the data', async () => {
  const db = await createDatabase();
  await db.exec(`
    SET session_replication_role = replica;
    INSERT INTO public.orders (user_id, status) VALUES (gen_random_uuid(), 'success');
    SET session_replication_role = origin;
    INSERT INTO public.wallet_ledger_entries (id, user_id) VALUES (50, gen_random_uuid());
  `);
  const rows = await runCheck(db, '#generated test\nmeta|pg_major|v=17');
  const orphan = rows.find((row) => row['对象'] === 'public.orders → public.users');
  assert.equal(orphan?.['结果'], '失败');
  assert.equal(orphan['实际'], '1');
  const sequence = rows.find((row) => row['对象'] === 'public.wallet_ledger_entries.id');
  assert.equal(sequence?.['结果'], '失败');
  await db.close();
});
