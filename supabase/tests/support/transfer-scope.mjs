// actualTables只接受根表结构描述；不连接数据库、不更新库存，也不授权导出任何字段。
export function assertTransferScopeCoverage(actualTables, { profile = 'local-replay' } = {}) {
  if (!Array.isArray(actualTables)) throw new TypeError('actualTables must be an array of root table descriptors');
  if (!['local-replay', 'production-2026-10-17'].includes(profile)) throw new TypeError('Unknown transfer schema profile');
  const inventory = profile === 'local-replay' ? TRANSFER_SCOPE_COVERAGE_INVENTORY : TRANSFER_PRODUCTION_COVERAGE_INVENTORY;
  const expected = new Map(inventory.map(table => [`${table.schema}.${table.name}`, table]));
  const seen = new Set();
  const issues = [];
  for (const [index, table] of actualTables.entries()) {
    if (!table || typeof table.schema !== 'string' || !table.schema || typeof table.name !== 'string' || !table.name) {
      issues.push({ kind: 'invalid-table', index });
      continue;
    }
    const key = `${table.schema}.${table.name}`;
    if (seen.has(key)) {
      issues.push({ kind: 'duplicate-table', table: key });
      continue;
    }
    seen.add(key);
    const descriptor = expected.get(key);
    if (!descriptor) {
      issues.push({ kind: 'unknown-table', table: key });
      continue;
    }
    if (!Array.isArray(table.columns)) {
      issues.push({ kind: 'invalid-columns', table: key });
      continue;
    }
    const columns = new Map(descriptor.columns.map(column => [column.name, column]));
    const seenColumns = new Set();
    for (const [columnIndex, column] of table.columns.entries()) {
      if (!column || typeof column.name !== 'string' || !column.name) {
        issues.push({ kind: 'invalid-column', table: key, index: columnIndex });
        continue;
      }
      const name = column.name;
      if (seenColumns.has(name)) {
        issues.push({ kind: 'duplicate-column', table: key, column: name });
        continue;
      }
      seenColumns.add(name);
      const original = columns.get(name);
      if (!original) {
        issues.push({ kind: 'unknown-column', table: key, column: name });
        continue;
      }
      if (column.type !== original.type) {
        issues.push({ kind: 'type-changed', table: key, column: name, expected: original.type, actual: column.type });
      }
      if (column.nullable !== original.nullable) {
        issues.push({ kind: 'nullable-changed', table: key, column: name, expected: original.nullable, actual: column.nullable });
      }
    }
    for (const column of descriptor.columns) {
      if (!seenColumns.has(column.name)) issues.push({ kind: 'missing-column', table: key, column: column.name });
    }
  }
  for (const key of expected.keys()) {
    if (!seen.has(key)) issues.push({ kind: 'missing-table', table: key });
  }
  if (issues.length) {
    const error = new Error(`Transfer scope coverage inventory mismatch (${issues.length}):\n${issues.map(issue => JSON.stringify(issue)).join('\n')}`);
    error.issues = issues;
    throw error;
  }
  return Object.freeze({
    tableCount: inventory.length,
    columnCount: inventory.reduce((count, table) => count + table.columns.length, 0),
    exportAuthorized: false,
  });
}
