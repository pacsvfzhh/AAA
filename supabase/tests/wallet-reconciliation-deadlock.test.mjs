class Session {
  constructor(name) {
    this.pending = null;
    this.name = name;
    this.process = spawn(join(pgBin, 'psql'), ['-X', '-qAt', '-U', 'postgres', '-h', directory, '-p', '55439', '-d', 'postgres'], {
      env: { PATH: process.env.PATH, LANG: 'C.UTF-8', PGAPPNAME: name },
      stdio: ['pipe', 'pipe', 'pipe'],
    });
    this.process.stdout.on('data', chunk => {
      if (!this.pending) return;
      this.pending.output += chunk.toString();
      const marker = `${this.pending.marker}\n`;
      const end = this.pending.output.indexOf(marker);
      if (end === -1) return;
      const pending = this.pending;
      this.pending = null;
      clearTimeout(pending.timer);
      const output = pending.output.slice(0, end).trim();
      if (/ERROR:|FATAL:/.test(pending.error)) pending.reject(new Error(pending.error));
      else pending.resolve({ output, warnings: pending.error });
    });
    this.process.stderr.on('data', chunk => {
      if (this.pending) this.pending.error += chunk.toString();
    });
    this.process.on('exit', code => {
      if (this.pending) {
        clearTimeout(this.pending.timer);
        this.pending.reject(new Error(`Local psql exited ${code}: ${this.pending.error}`));
        this.pending = null;
      }
    });
    sessions.push(this);
  }
  query(sql) {
    assert.equal(this.pending, null, `Concurrent commands on ${this.name}`);
    return new Promise((resolve, reject) => {
      const marker = `end_${randomUUID()}`;
      const timer = setTimeout(() => reject(new Error(`Local query timeout on ${this.name}`)), 10000);
      this.pending = { resolve, reject, marker, timer, output: '', error: '' };
      this.process.stdin.write(`${sql}\n\\echo ${marker}\n`);
    });
  }
  async json(sql) { return JSON.parse((await this.query(sql)).output); }
}

