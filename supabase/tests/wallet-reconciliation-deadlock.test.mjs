test('unpatched real ledger/reconciliation path reproduces a native 40P01 deadlock', async () => {
  await reset(false);
  const id = await seed();
  await worker.query(`BEGIN; SELECT user_id FROM wallets WHERE user_id='${id}' FOR UPDATE;`);
  await writer.query(`BEGIN; INSERT INTO wallet_transactions(user_id,type,amount) VALUES ('${id}','commission',5);`);
  const waitingUpdate = writer.query(`UPDATE wallets SET available_balance=available_balance+5 WHERE user_id='${id}';`);
  const writerResult = waitingUpdate.then(value => ({ value }), error => ({ error }));
  await waitForLock(writer.name);
  const workerResult = await worker.query('SELECT process_wallet_reconciliation_queue(100);').then(value => ({ value }), error => ({ error }));
  await worker.query('ROLLBACK;');
  const result = await writerResult;
  assert.match(`${workerResult.error?.message || ''} ${result.error?.message || ''}`, /40P01/);
  await writer.query('ROLLBACK;');
});

