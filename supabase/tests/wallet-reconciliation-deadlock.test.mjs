test('metadata, permissions and all other function bodies remain unchanged; unknown worker definitions are rejected', async () => {
  await reset(false);
  const catalog = () => observer.json(`SELECT json_agg(json_build_object('oid',p.oid,'name',p.proname,'metadata',to_jsonb(p)-'prosrc'-'proargdefaults','arguments',pg_get_function_arguments(p.oid),'body',p.prosrc) ORDER BY p.oid) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public';`);
  const previous = await catalog();
  await observer.query(migration);
  const next = await catalog();
  const oldWorker = previous.find(row => row.name === 'process_wallet_reconciliation_queue');
  const newWorker = next.find(row => row.name === 'process_wallet_reconciliation_queue');
  assert.deepEqual(newWorker.metadata, oldWorker.metadata);
  assert.equal(newWorker.arguments, oldWorker.arguments);
  assert.equal(newWorker.body, replacementBody);
  assert.deepEqual(next.filter(row => row.name !== newWorker.name), previous.filter(row => row.name !== oldWorker.name));
  assert.equal(await observer.json(`SELECT to_json(has_function_privilege('anon','public.process_wallet_reconciliation_queue(integer)','EXECUTE'));`), false);
  assert.equal(await observer.json(`SELECT to_json(has_function_privilege('service_role','public.process_wallet_reconciliation_queue(integer)','EXECUTE'));`), true);
  await assert.rejects(observer.query(migration), /differs from the reviewed definition/);
  await observer.query('ROLLBACK;');
  assert.equal((await catalog()).find(row => row.name === newWorker.name).body, replacementBody);
});

