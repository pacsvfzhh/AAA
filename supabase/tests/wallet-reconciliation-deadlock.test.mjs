  const gate = new Session('aplf-lock-gate');
  await gate.query('BEGIN; SELECT pg_advisory_xact_lock(701119,1);');
  const result = worker.json('SELECT process_wallet_reconciliation_queue(100);');
  await waitForLock(worker.name);
  await writer.query('BEGIN;');
  const enqueue = writer.query(`UPDATE wallet_reconciliation_queue SET requested_at=now() WHERE user_id='${id}';`);
  await waitForLock(writer.name);
  await gate.query('COMMIT;');
