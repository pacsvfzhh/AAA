async function waitForLock(name) {
  const deadline = Date.now() + 5000;
  while (Date.now() < deadline) {
    const waiting = await observer.json(`SELECT EXISTS(SELECT 1 FROM pg_stat_activity WHERE application_name='${name}' AND wait_event_type='Lock')::text;`);
    if (waiting) return;
    await new Promise(resolve => setTimeout(resolve, 15));
  }
  assert.fail(`${name} did not enter the expected native PostgreSQL lock wait`);
}
