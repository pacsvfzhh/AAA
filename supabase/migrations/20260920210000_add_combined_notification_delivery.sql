CREATE OR REPLACE FUNCTION public.send_admin_message_with_delivery(
  p_admin_session_token uuid,
  p_recipient_ids uuid[],
  p_title text,
  p_content text,
  p_delivery_mode text,
  p_priority text,
  p_reward_amount numeric,
  p_operation_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, private, pg_temp
AS $$
DECLARE
  v_message_type text;
  v_result jsonb;
  v_message_id uuid;
  v_existing_message_id uuid;
  v_registered_mode text;
BEGIN
  IF p_delivery_mode NOT IN ('realtime_only', 'login_only', 'realtime_with_login_fallback') THEN
    RAISE EXCEPTION 'Unsupported notification delivery mode.';
  END IF;

  SELECT (operation.result ->> 'message_id')::uuid
  INTO v_existing_message_id
  FROM public.financial_operations AS operation
  WHERE operation.operation_id = p_operation_id
    AND operation.operation_type = 'admin_message_send';

  IF v_existing_message_id IS NOT NULL THEN
    SELECT delivery_mode
    INTO v_registered_mode
    FROM public.messages
    WHERE id = v_existing_message_id;
  ELSE
    v_registered_mode := p_delivery_mode;
  END IF;

  INSERT INTO private.notification_delivery_operations(operation_id, delivery_mode)
  VALUES (p_operation_id, v_registered_mode)
  ON CONFLICT (operation_id) DO NOTHING;

  SELECT delivery_mode
  INTO v_registered_mode
  FROM private.notification_delivery_operations
  WHERE operation_id = p_operation_id
  FOR UPDATE;

  IF v_registered_mode IS DISTINCT FROM p_delivery_mode THEN
    RAISE EXCEPTION 'The operation ID was already used with a different delivery mode.';
  END IF;

  v_message_type := CASE p_delivery_mode
    WHEN 'realtime_only' THEN 'realtime'
    ELSE 'login_popup'
  END;

  v_result := public.send_admin_message_secure(
    p_admin_session_token,
    p_recipient_ids,
    p_title,
    p_content,
    v_message_type,
    p_priority,
    p_reward_amount,
    p_operation_id
  );

  v_message_id := (v_result ->> 'message_id')::uuid;

  UPDATE public.messages
  SET delivery_mode = p_delivery_mode
  WHERE id = v_message_id;

  RETURN v_result || jsonb_build_object('delivery_mode', p_delivery_mode);
END;
$$;

